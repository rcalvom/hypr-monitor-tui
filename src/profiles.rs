use crate::{
    backend,
    model::{Layout, validate},
};
use anyhow::{Result, ensure};
use serde::{Deserialize, Serialize};
use std::{
    fs,
    io::Write,
    path::{Path, PathBuf},
};

#[derive(Serialize, Deserialize)]
struct Profile {
    version: u32,
    #[serde(default)]
    name: String,
    #[serde(default)]
    created_at: String,
    #[serde(default)]
    updated_at: String,
    outputs: Layout,
}

pub struct Summary {
    pub name: String,
    pub created_at: String,
    pub updated_at: String,
    pub displays: usize,
    pub compatible: bool,
}

fn root() -> Result<PathBuf> {
    let base = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .filter(|p| p.is_absolute())
        .unwrap_or_else(|| {
            PathBuf::from(std::env::var_os("HOME").unwrap_or_default()).join(".config")
        });
    ensure!(base.is_absolute(), "HOME or XDG_CONFIG_HOME must be set");
    Ok(base.join("hypr-monitor-tui/profiles"))
}
fn path_at(root: &Path, name: &str, extension: &str) -> Result<PathBuf> {
    ensure!(
        !name.is_empty()
            && name.len() <= 80
            && name.trim() == name
            && name
                .chars()
                .all(|c| c.is_alphanumeric() || matches!(c, '-' | '_' | ' ')),
        "Use a name with letters, digits, spaces, - or _ (max 80 bytes)"
    );
    Ok(root.join(format!("{name}.{extension}")))
}
fn write_atomic(path: &Path, contents: &[u8]) -> Result<()> {
    let parent = path.parent().unwrap();
    fs::create_dir_all(parent)?;
    if path.exists() {
        fs::copy(
            path,
            path.with_extension(format!(
                "{}.bak",
                path.extension().unwrap().to_string_lossy()
            )),
        )?;
    }
    let mut temporary = tempfile::NamedTempFile::new_in(parent)?;
    temporary.write_all(contents)?;
    temporary.as_file().sync_all()?;
    temporary.persist(path)?;
    Ok(())
}
pub fn save(name: &str, layout: &Layout) -> Result<PathBuf> {
    save_at(&root()?, name, layout)
}
pub fn create(name: &str, layout: &Layout) -> Result<PathBuf> {
    let root = root()?;
    ensure!(
        !path_at(&root, name, "json")?.exists() && !path_at(&root, name, "lua")?.exists(),
        "A profile with this name already exists"
    );
    save_at(&root, name, layout)
}

pub fn rename(old: &str, new: &str) -> Result<()> {
    rename_at(&root()?, old, new)
}

fn rename_at(root: &Path, old: &str, new: &str) -> Result<()> {
    let source = path_at(root, old, "json")?;
    let target = path_at(root, new, "json")?;
    if old == new {
        return Ok(());
    }
    let source_lua = path_at(root, old, "lua")?;
    let target_lua = path_at(root, new, "lua")?;
    ensure!(
        !target.exists() && !target_lua.exists(),
        "A profile with this name already exists"
    );
    let mut profile: Profile = serde_json::from_slice(&fs::read(&source)?)?;
    ensure!(
        matches!(profile.version, 1 | 2),
        "Unsupported profile version"
    );
    profile.version = 2;
    profile.name = new.into();
    profile.updated_at = timestamp()?;
    let mut temporary = tempfile::NamedTempFile::new_in(root)?;
    temporary.write_all(&serde_json::to_vec_pretty(&profile)?)?;
    temporary.as_file().sync_all()?;
    temporary.persist_noclobber(&target)?;
    if source_lua.exists() {
        if let Err(error) = fs::hard_link(&source_lua, &target_lua) {
            fs::remove_file(&target)?;
            return Err(error.into());
        }
        fs::remove_file(source_lua)?;
    }
    fs::remove_file(source)?;
    Ok(())
}
fn save_at(root: &Path, name: &str, layout: &Layout) -> Result<PathBuf> {
    validate(layout)?;
    let json = path_at(root, name, "json")?;
    let now = timestamp()?;
    let created_at = if json.exists() {
        let old: Profile = serde_json::from_slice(&fs::read(&json)?)?;
        ensure!(
            matches!(old.version, 1 | 2),
            "Unsupported existing profile version"
        );
        if old.created_at.is_empty() {
            now.clone()
        } else {
            old.created_at
        }
    } else {
        now.clone()
    };
    let value = serde_json::to_vec_pretty(&Profile {
        version: 2,
        name: name.into(),
        created_at,
        updated_at: now,
        outputs: layout.clone(),
    })?;
    write_atomic(&json, &value)?;
    let lua_path = path_at(root, name, "lua")?;
    let lua = format!(
        "-- Generated by hypr-monitor-tui. Explicit opt-in; not automatically loaded.\n{}\n",
        layout
            .iter()
            .filter(|m| m.independent())
            .chain(layout.iter().filter(|m| m.enabled && m.mirror.is_some()))
            .chain(layout.iter().filter(|m| !m.enabled))
            .map(backend::lua)
            .collect::<Vec<_>>()
            .join("\n")
    );
    write_atomic(&lua_path, lua.as_bytes())?;
    Ok(json)
}
pub fn load(name: &str, current: &Layout) -> Result<Layout> {
    let profile: Profile = serde_json::from_slice(&fs::read(path_at(&root()?, name, "json")?)?)?;
    match_layout(profile, current)
}
fn match_layout(profile: Profile, current: &Layout) -> Result<Layout> {
    ensure!(
        matches!(profile.version, 1 | 2),
        "Unsupported profile version"
    );
    ensure!(
        profile.outputs.len() == current.len(),
        "Profile topology differs; connect the expected monitors first"
    );
    let mut output = profile.outputs;
    for m in &mut output {
        let now = current
            .iter()
            .find(|n| n.name == m.name && n.model == m.model)
            .ok_or_else(|| anyhow::anyhow!("Profile connector/model mismatch: {}", m.name))?;
        m.modes = now.modes.clone();
    }
    validate(&output)?;
    Ok(output)
}

pub fn list(current: &Layout) -> Result<Vec<Summary>> {
    list_at(&root()?, current)
}
fn list_at(root: &Path, current: &Layout) -> Result<Vec<Summary>> {
    if !root.exists() {
        return Ok(Vec::new());
    }
    let mut summaries = Vec::new();
    for entry in fs::read_dir(root)? {
        let path = entry?.path();
        if path.extension().and_then(|s| s.to_str()) != Some("json") {
            continue;
        }
        let name = path
            .file_stem()
            .and_then(|s| s.to_str())
            .ok_or_else(|| anyhow::anyhow!("Invalid profile filename"))?
            .to_string();
        let profile: Profile = serde_json::from_slice(&fs::read(&path)?)?;
        let summary = Summary {
            name,
            created_at: profile.created_at.clone(),
            updated_at: profile.updated_at.clone(),
            displays: profile.outputs.len(),
            compatible: match_layout(profile, current).is_ok(),
        };
        summaries.push(summary);
    }
    summaries.sort_by_key(|s| s.name.to_lowercase());
    Ok(summaries)
}
fn timestamp() -> Result<String> {
    use std::time::{SystemTime, UNIX_EPOCH};
    let seconds = SystemTime::now().duration_since(UNIX_EPOCH)?.as_secs() as libc::time_t;
    let mut time = std::mem::MaybeUninit::<libc::tm>::uninit();
    // gmtime_r initializes the caller-owned value on success; no shared buffer.
    ensure!(
        !unsafe { libc::gmtime_r(&seconds, time.as_mut_ptr()) }.is_null(),
        "Cannot format timestamp"
    );
    let time = unsafe { time.assume_init() };
    Ok(format!(
        "{:04}-{:02}-{:02}T{:02}:{:02}:{:02}Z",
        time.tm_year + 1900,
        time.tm_mon + 1,
        time.tm_mday,
        time.tm_hour,
        time.tm_min,
        time.tm_sec
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn named_profiles_survive_reload_and_preserve_backups() {
        let dir = tempfile::tempdir().unwrap();
        let mut layout = crate::ui::demo();
        let file = save_at(dir.path(), "Casa principal", &layout).unwrap();
        let old = fs::read(&file).unwrap();
        let initial: Profile = serde_json::from_slice(&old).unwrap();
        assert_eq!(initial.name, "Casa principal");
        assert!(initial.created_at.ends_with('Z'));
        layout[1].x = 2000;
        save_at(dir.path(), "Casa principal", &layout).unwrap();
        assert_eq!(fs::read(file.with_extension("json.bak")).unwrap(), old);
        let profile: Profile = serde_json::from_slice(&fs::read(file).unwrap()).unwrap();
        assert_eq!(profile.created_at, initial.created_at);
        assert_eq!(match_layout(profile, &layout).unwrap()[1].x, 2000);
        let summaries = list_at(dir.path(), &layout).unwrap();
        assert_eq!(summaries.len(), 1);
        assert!(summaries[0].compatible);
        assert!(!list_at(dir.path(), &layout[..1].to_vec()).unwrap()[0].compatible);
        assert!(save_at(dir.path(), "../escape", &layout).is_err());
    }
    #[test]
    fn rename_preserves_settings_and_rejects_collisions() {
        let dir = tempfile::tempdir().unwrap();
        let layout = crate::ui::demo();
        let old = save_at(dir.path(), "Casa", &layout).unwrap();
        let before: Profile = serde_json::from_slice(&fs::read(&old).unwrap()).unwrap();
        rename_at(dir.path(), "Casa", "Casa nueva").unwrap();
        assert!(!old.exists());
        assert!(!dir.path().join("Casa.lua").exists());
        assert!(dir.path().join("Casa nueva.lua").exists());
        let updated: Profile =
            serde_json::from_slice(&fs::read(dir.path().join("Casa nueva.json")).unwrap()).unwrap();
        assert_eq!(updated.name, "Casa nueva");
        assert_eq!(updated.created_at, before.created_at);
        assert_eq!(updated.outputs, before.outputs);
        save_at(dir.path(), "Oficina", &layout).unwrap();
        assert!(rename_at(dir.path(), "Casa nueva", "Oficina").is_err());
        assert!(dir.path().join("Casa nueva.json").exists());
    }
    #[test]
    fn legacy_profiles_remain_loadable() {
        let profile: Profile =
            serde_json::from_value(serde_json::json!({"version":1,"outputs":crate::ui::demo()}))
                .unwrap();
        assert!(match_layout(profile, &crate::ui::demo()).is_ok());
    }
}
